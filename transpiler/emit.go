type writer struct {
	b      strings.Builder
	indent int
}

func (w *writer) line(format string, args ...any) {
	for i := 0; i < w.indent; i++ {
		w.b.WriteByte('\t')
	}
	if len(args) == 0 {
		w.b.WriteString(format)
	} else {
		fmt.Fprintf(&w.b, format, args...)
	}
	w.b.WriteByte('\n')
}

func (w *writer) raw(s string) { w.b.WriteString(s) }

type pkgEmitter struct {
	c    *Compiler
	pkg  *packages.Package
	info *types.Info
	fset *token.FileSet

	imports    map[string]string // package path -> local alias
	importPkgs map[string]*types.Package
	importList []string

	tyIndex map[string]int // type string -> TY index
	tyDefs  []string
	tyTypes []types.Type // the type behind each TY slot, to re-register inlined code

	tmp int

	types   writer // named type declarations
	defs    writer // type definitions and method tables
	funcs   writer // functions
	inits   writer // variable initialization and init()
	methods writer // method dispatch tables (after functions exist)
	hasInit bool

	localTypes int      // slots in the module's LT cache of function-local types
	hoisted    []string // function literals that capture nothing, defined once in the module's FN table
}

func (c *Compiler) emitPackage(p *packages.Package) string {
	e := &pkgEmitter{
		c:       c,
		pkg:     p,
		info:    p.TypesInfo,
		fset:    p.Fset,
		imports: map[string]string{},
		tyIndex: map[string]int{},
	}
	e.emit()
	var out strings.Builder
	fmt.Fprintf(&out, "-- Code generated by golua from %s. DO NOT EDIT.\n", p.PkgPath)
	out.WriteString("local rt = require('rt')\n")
	out.WriteString(prologue)
	fmt.Fprintf(&out, "local P = rt.package(%s)\n", luaString(p.PkgPath))
	out.WriteString("local TY = rt.lazytypes()\n")
	if e.localTypes > 0 {
		out.WriteString("local LT = {}\n")
	}
	if len(e.hoisted) > 0 {
		out.WriteString("local FN = {}\n")
	}
	for _, path := range e.importList {
		fmt.Fprintf(&out, "local %s = rt.import(%s)\n", e.imports[path], luaString(luaModuleName(path)))
	}
	out.WriteString(e.types.b.String())
	for i, d := range e.tyDefs {
		fmt.Fprintf(&out, "TY[%d] = function() return %s end\n", i+1, d)
	}
	out.WriteString(e.defs.b.String())
	out.WriteString(e.funcs.b.String())
	// Functions only run once the module has loaded, after these are defined.
	for i, code := range e.hoisted {
		fmt.Fprintf(&out, "FN[%d] = %s\n", i+1, code)
	}
	// Patches replace functions before method tables capture them.
	if c.hasPatch(p.PkgPath) {
		fmt.Fprintf(&out, "require(%s)(P)\n", luaString(luaModuleName(p.PkgPath)+"_patch"))
	}
	out.WriteString(e.methods.b.String())
	out.WriteString("function P.__init()\n")
	out.WriteString("\tP.__init = nil\n")
	out.WriteString(e.inits.b.String())
	out.WriteString("end\n")
	out.WriteString("return P\n")
	return out.String()
}

// Local aliases for hot runtime helpers, shared by every generated module.
const prologue = `local setmetatable, getmetatable, rawget, type, select, error = setmetatable, getmetatable, rawget, type, select, error
local sbyte, ssub, fmod, LEN, E, NIL, NILKEY = string.byte, string.sub, math.fmod, rt.LEN, rt.E, rt.NIL, rt.NILKEY
local append, append1, mkslice, slice, mset, nn = rt.append, rt.append1, rt.mkslice, rt.slice, rt.mset, rt.nn
local ieq, box, typeof, idiv, call = rt.ieq, rt.box, rt.typeof, rt.idiv, rt.call
local band, bor, bxor, bnot, lshift, rshift, arshift, tobit = bit.band, bit.bor, bit.bxor, bit.bnot, bit.lshift, bit.rshift, bit.arshift, bit.tobit
local floor, imul, udiv, I64, U64 = math.floor, rt.imul, rt.udiv, rt.I64, rt.U64
`

func (e *pkgEmitter) importAlias(pkg *types.Package) string {
	if pkg == e.pkg.Types {
		return "P"
	}
	if a, ok := e.imports[pkg.Path()]; ok {
		return a
	}
	base := pkg.Name()
	if !isASCII(base) {
		base = "pkg"
	}
	alias := "__" + base
	taken := map[string]bool{}
	for _, a := range e.imports {
		taken[a] = true
	}
	for i := 2; taken[alias]; i++ {
		alias = fmt.Sprintf("__%s%d", base, i)
	}
	e.imports[pkg.Path()] = alias
	if e.importPkgs == nil {
		e.importPkgs = map[string]*types.Package{}
	}
	e.importPkgs[pkg.Path()] = pkg
	e.importList = append(e.importList, pkg.Path())
	return alias
}

func (e *pkgEmitter) pos(p token.Pos) token.Position { return e.fset.Position(p) }

func (e *pkgEmitter) newTmp(prefix string) string {
	e.tmp++
	return fmt.Sprintf("__%s%d", prefix, e.tmp)
}

func (e *pkgEmitter) emit() {
	// Make sure every imported package is initialized before this one, even if
	// only used for side effects.
	var paths []string
	for path := range e.pkg.Imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		if e.c.byPath[path] != nil && path != "unsafe" && path != "C" {
			e.importAlias(e.pkg.Imports[path].Types)
		}
	}

	var funcs []*ast.FuncDecl
	var initFuncs []*ast.FuncDecl
	for _, f := range e.pkg.Syntax {
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.GenDecl:
				if d.Tok == token.TYPE {
					for _, s := range d.Specs {
						e.typeSpec(s.(*ast.TypeSpec), &e.types, &e.defs, "P."+luaIdent(s.(*ast.TypeSpec).Name.Name), true)
					}
				}
			case *ast.FuncDecl:
				if d.Recv == nil && d.Name.Name == "init" {
					initFuncs = append(initFuncs, d)
				} else {
					funcs = append(funcs, d)
				}
			}
		}
	}
	for _, d := range funcs {
		e.funcDecl(d)
	}

	// Embedded files.
	embeds := e.embedVars()

	// Variables without initializers still need zero values.
	scope := e.pkg.Types.Scope()
	for _, name := range scope.Names() {
		v, ok := scope.Lookup(name).(*types.Var)
		if !ok {
			continue
		}
		if e.initialized(v) {
			continue
		}
		ref := e.pkgVarRef(v)
		if spec, ok := embeds[v]; ok {
			e.inits.line("\t%s = %s", ref, spec)
			continue
		}
		zero := e.newFuncCtx(nil, nil).zeroValue(v.Type())
		if e.c.boxed[v] {
			e.inits.line("\tP.%s = {v = %s}", luaIdent(v.Name()), zero)
		} else if zero != "nil" {
			e.inits.line("\t%s = %s", ref, zero)
		}
	}
	// Package-level variables in dependency order.
	for _, init := range e.info.InitOrder {
		e.varInit(init, embeds)
	}
	for i, d := range initFuncs {
		name := fmt.Sprintf("__init%d", i)
		fc := e.newFuncCtx(nil, e.info.Defs[d.Name].(*types.Func).Type().(*types.Signature))
		e.funcs.line("local function %s()", name)
		fc.body(&e.funcs, d.Body)
		e.funcs.line("end")
		e.inits.line("\t%s()", name)
	}
}

func (e *pkgEmitter) initialized(v *types.Var) bool {
	for _, init := range e.info.InitOrder {
		for _, lhs := range init.Lhs {
			if lhs == v {
				return true
			}
		}
	}
	return false
}

func (e *pkgEmitter) pkgVarRef(v *types.Var) string {
	alias := e.importAlias(v.Pkg())
	ref := alias + "." + luaIdent(v.Name())
	if e.c.boxed[v] {
		ref += ".v"
	}
	return ref
}

func (e *pkgEmitter) varInit(init *types.Initializer, embeds map[*types.Var]string) {
	fc := e.newFuncCtx(nil, nil)
	w := &writer{indent: 1}
	if len(init.Lhs) == 1 {
		v := init.Lhs[0]
		val := fc.convertExpr(init.Rhs, v.Type())
		if !fc.isFresh(init.Rhs) {
			val = fc.cloneIfNeeded(val, v.Type())
		}
		if v.Name() == "_" {
			discardLine(w, val)
		} else if e.c.boxed[v] {
			w.line("P.%s = {v = %s}", luaIdent(v.Name()), val)
		} else {
			w.line("P.%s = %s", luaIdent(v.Name()), val)
		}
	} else {
		var tmps []string
		for range init.Lhs {
			tmps = append(tmps, e.newTmp("t"))
		}
		w.line("local %s = %s", strings.Join(tmps, ", "), fc.expr(init.Rhs))
		for i, v := range init.Lhs {
			if v.Name() == "_" {
				continue
			}
			if e.c.boxed[v] {
				w.line("P.%s = {v = %s}", luaIdent(v.Name()), tmps[i])
			} else {
				w.line("P.%s = %s", luaIdent(v.Name()), tmps[i])
			}
		}
	}
	e.inits.raw(fc.flushPre(1))
	e.inits.raw(w.b.String())
}

// embedVars maps //go:embed variables to Lua expressions that load the embedded data.
func (e *pkgEmitter) embedVars() map[*types.Var]string {
	res := map[*types.Var]string{}
	for _, f := range e.pkg.Syntax {
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.VAR {
				continue
			}
			for _, s := range gd.Specs {
				vs := s.(*ast.ValueSpec)
				var patterns []string
				for _, cg := range []*ast.CommentGroup{gd.Doc, vs.Doc} {
					if cg == nil {
						continue
					}
					for _, cm := range cg.List {
						if strings.HasPrefix(cm.Text, "//go:embed ") {
							patterns = append(patterns, strings.Fields(strings.TrimPrefix(cm.Text, "//go:embed "))...)
						}
					}
				}
				if len(patterns) == 0 || len(vs.Names) != 1 {
					continue
				}
				v := e.info.Defs[vs.Names[0]].(*types.Var)
				kind := "fs"
				switch t := v.Type().Underlying().(type) {
				case *types.Basic:
					kind = "string"
				case *types.Slice:
					_ = t
					kind = "bytes"
				}
				var quoted []string
				for _, p := range patterns {
					quoted = append(quoted, luaString(p))
				}
				res[v] = fmt.Sprintf("rt.embed(%s, %s, {%s})", luaString(luaModuleName(e.pkg.PkgPath)), luaString(kind), strings.Join(quoted, ", "))
				e.c.copyEmbeds(e.pkg)
			}
		}
	}
	return res
}

func (c *Compiler) copyEmbeds(p *packages.Package) {
	if c.embedOut == "" || c.embedCopied[p.PkgPath] {
		return
	}
	if c.embedCopied == nil {
		c.embedCopied = map[string]bool{}
	}
	c.embedCopied[p.PkgPath] = true
	dir := filepath.Dir(p.GoFiles[0])
	for _, f := range p.EmbedFiles {
		rel, err := filepath.Rel(dir, f)
		if err != nil {
			continue
		}
		dst := filepath.Join(c.embedOut, filepath.FromSlash(luaModuleName(p.PkgPath)), rel)
		data, err := os.ReadFile(f)
		if err != nil {
			fatalf("embed: %v", err)
		}
		os.MkdirAll(filepath.Dir(dst), 0o755)
		writeIfChanged(dst, string(data))
	}
}

