// Functions

func (e *pkgEmitter) funcDecl(d *ast.FuncDecl) {
	if d.Name.Name == "_" {
		// Blank functions exist only for compile-time checks.
		return
	}
	fn := e.info.Defs[d.Name].(*types.Func)
	sig := fn.Type().(*types.Signature)
	name := e.funcKey(fn)
	fc := e.newFuncCtx(nil, sig)
	var params []string
	// Generic functions and methods of generic types receive type descriptors first.
	if sig.RecvTypeParams().Len() > 0 {
		for i := 0; i < sig.RecvTypeParams().Len(); i++ {
			params = append(params, typeParamName(sig.RecvTypeParams().At(i)))
		}
	}
	for i := 0; i < sig.TypeParams().Len(); i++ {
		params = append(params, typeParamName(sig.TypeParams().At(i)))
	}
	if d.Recv != nil {
		params = append(params, fc.paramNames(d.Recv)...)
	}
	params = append(params, fc.paramNames(d.Type.Params)...)
	if d.Body == nil {
		e.funcs.line("function P.%s(...) rt.nobody(%s) end", name, luaString(e.pkg.PkgPath+"."+name))
		return
	}
	fc.params = params
	fc.topLevel = true
	e.funcs.line("function P.%s(%s)", name, strings.Join(params, ", "))
	e.funcs.indent++
	fc.prologue(&e.funcs, d.Recv, d.Type)
	e.funcs.indent--
	fc.body(&e.funcs, d.Body)
	e.funcs.line("end")
}

// funcKey is the key in the package table holding a function or method.
func (e *pkgEmitter) funcKey(fn *types.Func) string {
	return funcKeyOf(fn)
}

func funcKeyOf(fn *types.Func) string {
	sig := fn.Type().(*types.Signature)
	if sig.Recv() == nil {
		return luaIdent(fn.Name())
	}
	rt := sig.Recv().Type()
	if p, ok := types.Unalias(rt).(*types.Pointer); ok {
		rt = p.Elem()
	}
	var tname string
	switch t := types.Unalias(rt).(type) {
	case *types.Named:
		tname = t.Origin().Obj().Name()
	default:
		tname = "anon"
	}
	return luaIdent(tname) + "__" + luaIdent(fn.Name())
}

// typeRef returns a Lua expression evaluating to the runtime descriptor of t,
// hoisting type constants into the module's lazy TY table when possible.
func (e *pkgEmitter) typeRef(fc *funcCtx, t types.Type) string {
	if !e.hoistable(t) {
		return fc.typeExpr(t)
	}
	key := types.TypeString(t, nil)
	if i, ok := e.tyIndex[key]; ok {
		return fmt.Sprintf("TY[%d]", i)
	}
	// Reserve the slot first; typeExpr may register dependencies.
	inner := e.newFuncCtx(nil, nil)
	expr := inner.typeExprRaw(t)
	if strings.HasPrefix(expr, "rt.") && !strings.Contains(expr, "(") {
		return expr
	}
	if _, ok := types.Unalias(t).(*types.Named); ok && !strings.Contains(expr, "(") {
		return expr
	}
	e.tyDefs = append(e.tyDefs, expr)
	e.tyTypes = append(e.tyTypes, t)
	i := len(e.tyDefs)
	e.tyIndex[key] = i
	return fmt.Sprintf("TY[%d]", i)
}

// hoistable reports whether t can be computed once at module level.
func (e *pkgEmitter) hoistable(t types.Type) bool {
	ok := true
	var visit func(t types.Type)
	seen := map[types.Type]bool{}
	visit = func(t types.Type) {
		if !ok || seen[t] {
			return
		}
		seen[t] = true
		switch t := types.Unalias(t).(type) {
		case *types.TypeParam:
			ok = false
		case *types.Named:
			if t.Obj().Parent() != nil && t.Obj().Pkg() != nil && t.Obj().Parent() != t.Obj().Pkg().Scope() {
				ok = false // function-local type
				return
			}
			if t.Obj().Pkg() == nil {
				return
			}
			args := t.TypeArgs()
			for i := 0; i < args.Len(); i++ {
				visit(args.At(i))
			}
		case *types.Pointer:
			visit(t.Elem())
		case *types.Slice:
			visit(t.Elem())
		case *types.Array:
			visit(t.Elem())
		case *types.Map:
			visit(t.Key())
			visit(t.Elem())
		case *types.Chan:
			visit(t.Elem())
		case *types.Signature:
			for i := 0; i < t.Params().Len(); i++ {
				visit(t.Params().At(i).Type())
			}
			for i := 0; i < t.Results().Len(); i++ {
				visit(t.Results().At(i).Type())
			}
		case *types.Struct:
			for i := 0; i < t.NumFields(); i++ {
				visit(t.Field(i).Type())
			}
		case *types.Interface:
			for i := 0; i < t.NumMethods(); i++ {
				visit(t.Method(i).Type())
			}
		}
	}
	visit(t)
	return ok
}

// isStructType reports whether t itself (not a pointer to it) is a struct type.
func isStructType(t types.Type) bool {
	_, ok := t.Underlying().(*types.Struct)
	return ok
}
