// Types

// typeSpec emits a named type declaration. ref is the Lua expression that will
// hold the descriptor (P.Name at package level, a local inside functions).
func (e *pkgEmitter) typeSpec(spec *ast.TypeSpec, decl, def *writer, ref string, pkgLevel bool) {
	e.typeSpecAs(spec, decl, def, ref, pkgLevel, !pkgLevel, "")
}

// typeSpecAs emits a type declaration; declare makes ref a new Lua local rather than assigning it.
// typeArgs, when set, is a Lua expression for the instantiation's type argument names, as Go names
// a local type declared in a generic function after the function's type arguments.
func (e *pkgEmitter) typeSpecAs(spec *ast.TypeSpec, decl, def *writer, ref string, pkgLevel, declare bool, typeArgs string) {
	obj := e.info.Defs[spec.Name].(*types.TypeName)
	if obj.IsAlias() {
		if pkgLevel {
			return
		}
		return
	}
	named := obj.Type().(*types.Named)
	tname := obj.Name()
	if !pkgLevel {
		tname = fmt.Sprintf("%s·%d", tname, e.pos(spec.Pos()).Line)
	}
	full := e.pkg.Types.Name() + "." + tname
	if named.TypeParams().Len() > 0 {
		var params []string
		for i := 0; i < named.TypeParams().Len(); i++ {
			params = append(params, typeParamName(named.TypeParams().At(i)))
		}
		fc := e.newFuncCtx(nil, nil)
		inner := &writer{indent: decl.indent + 1}
		e.defineType(fc, named, "__T", inner, nil)
		prefix := "local "
		if !declare {
			prefix = ""
		}
		decl.line("%s%s = rt.generic(%s, %s, %d, function(__T, %s)", prefix, ref, luaString(e.pkg.PkgPath), luaString(full), len(params), strings.Join(params, ", "))
		decl.raw(fc.flushPre(decl.indent + 1))
		decl.raw(inner.b.String())
		decl.line("end)")
		return
	}
	prefix := "local "
	if !declare {
		prefix = ""
	}
	nameExpr := luaString(full)
	if typeArgs != "" {
		nameExpr = fmt.Sprintf("%s .. '[' .. %s .. ']'", luaString(full), typeArgs)
	}
	decl.line("%s%s = rt.named(%s, %s, %s)", prefix, ref, luaString(e.pkg.PkgPath), nameExpr, luaString(kindName(named.Underlying())))
	fc := e.newFuncCtx(nil, nil)
	inner := &writer{indent: def.indent}
	var mw *writer
	if pkgLevel {
		mw = &e.methods
	}
	e.defineType(fc, named, ref, inner, mw)
	def.raw(fc.flushPre(def.indent))
	def.raw(inner.b.String())
}

func kindName(t types.Type) string {
	switch u := t.(type) {
	case *types.Basic:
		return basicKind(u)
	case *types.Struct:
		return "struct"
	case *types.Pointer:
		return "ptr"
	case *types.Slice:
		return "slice"
	case *types.Array:
		return "array"
	case *types.Map:
		return "map"
	case *types.Chan:
		return "chan"
	case *types.Signature:
		return "func"
	case *types.Interface:
		return "interface"
	}
	return "invalid"
}

func basicKind(b *types.Basic) string {
	switch b.Kind() {
	case types.Bool, types.UntypedBool:
		return "bool"
	case types.Int, types.UntypedInt:
		return "int"
	case types.Int8:
		return "int8"
	case types.Int16:
		return "int16"
	case types.Int32, types.UntypedRune:
		return "int32"
	case types.Int64:
		return "int64"
	case types.Uint:
		return "uint"
	case types.Uint8:
		return "uint8"
	case types.Uint16:
		return "uint16"
	case types.Uint32:
		return "uint32"
	case types.Uint64:
		return "uint64"
	case types.Uintptr:
		return "uintptr"
	case types.Float32:
		return "float32"
	case types.Float64, types.UntypedFloat:
		return "float64"
	case types.Complex64:
		return "complex64"
	case types.Complex128, types.UntypedComplex:
		return "complex128"
	case types.String, types.UntypedString:
		return "string"
	case types.UnsafePointer:
		return "unsafeptr"
	case types.UntypedNil:
		return "nil"
	}
	return "invalid"
}

// defineType emits the underlying definition and method tables of a named type.
func (e *pkgEmitter) defineType(fc *funcCtx, named *types.Named, ref string, w, mw *writer) {
	under := named.Underlying()
	switch u := under.(type) {
	case *types.Struct:
		w.line("rt.defineStruct(%s, %s)", ref, fc.structFieldList(u))
	default:
		if isNarrow64(named) {
			// The 64-bit kind, with its values held as plain Lua numbers.
			w.line("rt.define(%s, rt.%sd)", ref, basicKind(under.(*types.Basic)))
		} else {
			w.line("rt.define(%s, %s)", ref, fc.typeExpr(under))
		}
	}
	if mw == nil {
		mw = w
	}
	e.methodTables(fc, named, ref, mw)
}

// methodTables emits the dynamic dispatch tables for T and *T.
func (e *pkgEmitter) methodTables(fc *funcCtx, named *types.Named, ref string, w *writer) {
	if isInterface(named) {
		return
	}
	_, isStruct := named.Underlying().(*types.Struct)
	vset := types.NewMethodSet(named)
	pset := types.NewMethodSet(types.NewPointer(named))
	if pset.Len() == 0 {
		return
	}
	w.line("rt.methods(%s, {", ref)
	for i := 0; i < vset.Len(); i++ {
		sel := vset.At(i)
		w.line("\t%s = %s,", methodKey(sel.Obj().Name()), e.methodAdapter(fc, named, sel, false, isStruct))
	}
	w.line("}, {")
	for i := 0; i < pset.Len(); i++ {
		sel := pset.At(i)
		w.line("\t%s = %s,", methodKey(sel.Obj().Name()), e.methodAdapter(fc, named, sel, true, isStruct))
	}
	w.line("})")
}

// methodAdapter returns a function taking the receiver in its dispatch representation:
// the struct table for structs (value or pointer), the plain value for non-struct values,
// and the {v=...} box for pointers to non-struct types.
func (e *pkgEmitter) methodAdapter(fc *funcCtx, named *types.Named, sel *types.Selection, ptr, isStruct bool) string {
	fn := sel.Obj().(*types.Func)
	idx := sel.Index()
	recvExpr := "r"
	var t types.Type = named
	if ptr {
		t = types.NewPointer(named)
	}
	_ = isStruct
	// Walk embedded fields.
	for _, i := range idx[:len(idx)-1] {
		st := derefStruct(t)
		f := st.Field(i)
		info := e.c.layout(st).fields[i]
		if !info.flat {
			recvExpr = info.access(recvExpr)
		}
		t = f.Type()
	}
	sig := fn.Type().(*types.Signature)
	recvT := sig.Recv().Type()
	_, wantPtr := recvT.Underlying().(*types.Pointer)
	if _, isNamedPtr := types.Unalias(recvT).(*types.Pointer); !isNamedPtr {
		wantPtr = false
	}
	_, havePtr := types.Unalias(t).(*types.Pointer)
	if isInterface(t) {
		return fmt.Sprintf("function(r, ...) return %s:%s(...) end", recvExpr, methodKey(fn.Name()))
	}
	baseStruct := isStructish(t)
	if !wantPtr && havePtr && !baseStruct {
		recvExpr += ".v"
	}
	target := fc.funcRef(fn)
	targs := fc.recvTypeArgs(t)
	if recvExpr == "r" && len(targs) == 0 {
		return target
	}
	args := append(targs, recvExpr)
	return fmt.Sprintf("function(r, ...) return %s(%s, ...) end", target, strings.Join(args, ", "))
}

func isStructish(t types.Type) bool {
	t = types.Unalias(t)
	if p, ok := t.(*types.Pointer); ok {
		t = p.Elem()
	}
	_, ok := t.Underlying().(*types.Struct)
	return ok
}

func derefStruct(t types.Type) *types.Struct {
	t = types.Unalias(t)
	if p, ok := t.Underlying().(*types.Pointer); ok {
		t = p.Elem()
	}
	st, _ := t.Underlying().(*types.Struct)
	return st
}

func typeParamName(tp *types.TypeParam) string {
	return "__tp_" + luaIdent(tp.Obj().Name())
}

